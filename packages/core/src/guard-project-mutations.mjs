export function guardProjectMutations(application, ports) {
  const guarded = { ...application };
  for (const name of PROJECT_MUTATION_METHODS) {
    const useCase = application[name];
    if (typeof useCase !== "function") continue;
    guarded[name] = async (input = {}) => {
      if (input.projectId) {
        const session = await ports.projects.getProjectControlSession(input.projectId);
        assertProjectMutationAllowed(session, input.operationContext);
      }
      return useCase(input);
    };
  }
  return guarded;
}
